"""Build HEXPRESS batch .conf files and run the batch executables.

The conf format is the one HEXPRESS itself writes when exporting a batch
configuration (see _python/_tests_db/_installations/hexpress/*.conf in the
install dir): keyword lines, with INFILENAMES/OUTFILENAME taking their values
on following lines, terminated by END.
"""

from __future__ import annotations

import re
import subprocess
import time
from pathlib import Path

SCRIPT_RETURN_RE = re.compile(r"SCRIPT_RETURN_VALUE\s+(-?\d+)")

# HEXPRESS 10.1 batch mode swallows the embedded Python's stdout (Session.py
# routes it to a Tcl sink that goes nowhere without a GUI). This Py2 wrapper
# execfile()s the user script with stdout redirected to a buffer, then writes
# the buffer and the SCRIPT_RETURN_VALUE (0 when unset, 1 on exception) to
# files the MCP server reads back after the run.
SCRIPT_WRAPPER = r'''\
# -*- coding: utf-8 -*-
# generated by hexpress-mcp - do not edit
import sys, traceback, re
try:
    import StringIO
except ImportError:
    import io as StringIO
__buf = StringIO.StringIO()
__old_stdout = sys.stdout
__old_stderr = sys.stderr
sys.stdout = __buf
sys.stderr = __buf
__err = None
try:
    execfile(r"{script}")
except Exception:
    traceback.print_exc()
    __err = sys.exc_info()
sys.stdout = __old_stdout
sys.stderr = __old_stderr
__out = open(r"{log}", "w")
__out.write(__buf.getvalue())
__out.close()
__m = re.search(r"SCRIPT_RETURN_VALUE\s+(-?\d+)", __buf.getvalue())
if __m:
    __rv = int(__m.group(1))
elif __err is None:
    __rv = 0
else:
    __rv = 1
open(r"{result}", "w").write(str(__rv))
'''


def build_script_wrapper(script: Path, log: Path, result: Path) -> str:
    return SCRIPT_WRAPPER.format(script=str(script), log=str(log), result=str(result))


class BatchError(Exception):
    """A batch executable failed or timed out."""


def build_conf(
    input_files: list[str],
    output_mesh: str,
    base_h: float | None = None,
    num_boundary_layers: int | None = None,
    boundary_layer_transition: int | None = None,
    refinements: dict[str, list[int]] | None = None,
    boundary_conditions: dict[str, str] | None = None,
    mark_all_outer: bool = False,
    suppress_prefix: bool = True,
    full_hexa: bool = False,
    exact_meshing: bool = False,
    s2v_mesh: bool = False,
    s2v_surface_only: bool = False,
    extra_lines: list[str] | None = None,
) -> str:
    """Render a HEXPRESS batch configuration.

    refinements: name -> [initial_level, min_level] for LOCALREFINEMENTDEFINITION.
    boundary_conditions: name -> BC type (e.g. SOL, INL, OUT, SYM) for BCDEFINITION.
    Unknown/advanced keywords can be passed verbatim via extra_lines.
    """
    lines: list[str] = ["#File generated by hexpress-mcp", ""]
    lines.append("INFILENAMES")
    lines.append(str(len(input_files)))
    lines.extend(input_files)
    lines.append("")
    lines.append("OUTFILENAME")
    lines.append(output_mesh)
    lines.append("")
    if suppress_prefix:
        lines.append("SUPPRESSPREFIX")
    if mark_all_outer:
        lines.append("MARKALLOUTER")
    if base_h is not None:
        lines.append(f"BASEH {base_h}")
    if exact_meshing:
        lines.append("EXACTMESHING")
    if full_hexa:
        lines.append("GENERATEFULLHEXAMESH")
    for name, levels in (refinements or {}).items():
        lv = [*levels, 0, 0]
        lines.append(f"LOCALREFINEMENTDEFINITION {name} {lv[0]} {lv[1]}")
    if num_boundary_layers is not None:
        lines.append(f"NUMBNDLAYERS {num_boundary_layers}")
    if boundary_layer_transition is not None:
        lines.append(f"BNDLAYERTRANSITION {boundary_layer_transition}")
    for name, bc_type in (boundary_conditions or {}).items():
        lines.append(f"BCDEFINITION {name} {bc_type}")
    if s2v_mesh:
        lines.append("GENERATES2VMESH")
        if s2v_surface_only:
            lines.append("S2VPARAM GENERATESURFACEMESH MIXED")
    for line in extra_lines or []:
        lines.append(line)
    lines.append("END")
    lines.append("")
    return "\n".join(lines)


def parse_script_return(log: str) -> int | None:
    m = SCRIPT_RETURN_RE.search(log or "")
    return int(m.group(1)) if m else None


_MESH_INT_RE = re.compile(r"^Number of ([\w. ]+?)\s{2,}(\d+)$", re.M)
_MESH_FLT_RE = re.compile(r"^\s*(\w[\w .:-]*?)[\s:]{1,}(-?\d+\.\d+(?:e[-+]?\d+)?)", re.M)


def parse_mesh_stats(log: str) -> dict:
    """Pull the HEXPRESS summary/quality block out of a batch log:
    cell counts, quality metrics and overall time, as flat dicts."""
    log = log or ""
    ints = {m.group(1).strip().lower().replace(" ", "_"): int(m.group(2))
            for m in _MESH_INT_RE.finditer(log)}
    wanted = ("minimal edge-length", "average edge-length", "maximal edge-length",
              "max equiangular skewness", "max adjacent volume ratio",
              "max expansion ratio", "overall time", "overall cpu time")
    flts = {}
    for m in _MESH_FLT_RE.finditer(log):
        key = m.group(1).strip().lower().rstrip(":").strip()
        if key in wanted:
            flts[key.replace(" ", "_").replace("-", "_")] = float(m.group(2))
    return {"counts": ints, "quality": flts}


def tail(text: str, n: int = 120) -> str:
    lines = (text or "").splitlines()
    return "\n".join(lines[-n:])


def run_exe(
    cmd: list[str],
    timeout: int,
    env: dict[str, str] | None = None,
    cwd: str | Path | None = None,
    keep_full_log: bool = False,
) -> dict:
    """Run one NUMECA executable, capturing combined output. Never raises:
    failures are reported in the returned dict."""
    started = time.time()
    try:
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            encoding="gbk",
            errors="replace",
            timeout=timeout,
            env=env,
            cwd=cwd,
            check=False,
        )
        log = (proc.stdout or "") + ("\n" + proc.stderr if proc.stderr else "")
        result = {
            "command": " ".join(str(c) for c in cmd),
            "returncode": proc.returncode,
            "timed_out": False,
            "elapsed_s": round(time.time() - started, 1),
            "log_tail": tail(log),
            "script_return_value": parse_script_return(log),
        }
        if keep_full_log:
            result["log_full"] = log
        return result
    except subprocess.TimeoutExpired as exc:
        log = ""
        for part in (exc.stdout, exc.stderr):
            if isinstance(part, bytes):
                log += part.decode("utf-8", "replace")
            elif part:
                log += str(part)
        return {
            "command": " ".join(str(c) for c in cmd),
            "returncode": None,
            "timed_out": True,
            "elapsed_s": round(time.time() - started, 1),
            "log_tail": tail(log),
            "script_return_value": None,
        }
